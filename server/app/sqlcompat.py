import re
import sqlite3


def translate(sql):
    text = sql.strip()
    folded = text.upper()
    if folded.startswith("PRAGMA BUSY_TIMEOUT"):
        return "SELECT 1 WHERE 1 = 0", ()
    if folded.startswith("PRAGMA TABLE_INFO"):
        name = re.search(r"\(([^)]+)\)", text).group(1).strip("'\"")
        return (
            "SELECT 0, column_name, data_type, CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END, "
            "column_default, 0 FROM information_schema.columns WHERE table_name = %s ORDER BY ordinal_position",
            (name,),
        )
    text = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", text, flags=re.I)
    text = re.sub(r"AUTOINCREMENT", "", text, flags=re.I)
    text = re.sub(r"COLLATE NOCASE", "", text, flags=re.I)
    text = re.sub(r"\bBLOB\b", "BYTEA", text, flags=re.I)
    if folded.startswith("INSERT OR IGNORE"):
        text = re.sub(r"INSERT OR IGNORE", "INSERT", text, count=1, flags=re.I) + " ON CONFLICT DO NOTHING"
    elif folded.startswith("INSERT OR REPLACE INTO ARCHIVE"):
        text = re.sub(r"INSERT OR REPLACE", "INSERT", text, count=1, flags=re.I)
        text += " ON CONFLICT (entry_id) DO UPDATE SET name = EXCLUDED.name, data = EXCLUDED.data, updated_at = EXCLUDED.updated_at"
    text = text.replace("?", "%s")
    return text, None


class Result:
    def __init__(self, rows=None, rowcount=0):
        self.rows = list(rows or [])
        self.rowcount = rowcount

    def __iter__(self):
        return self

    def __next__(self):
        if not self.rows:
            raise StopIteration
        return self.rows.pop(0)

    def fetchone(self):
        return self.rows.pop(0) if self.rows else None

    def fetchall(self):
        rows = self.rows
        self.rows = []
        return rows


class Connection:
    def __init__(self, raw):
        self.raw = raw
        self._broken = False

    def execute(self, sql, params=()):
        translated, extra = translate(sql)
        if extra is not None:
            params = extra
        try:
            cursor = self.raw.cursor()
            cursor.execute(translated, tuple(params))
            rows = cursor.fetchall() if cursor.description else []
            return Result(rows, cursor.rowcount)
        except Exception as error:
            self._broken = True
            if getattr(error, "sqlstate", "") == "23505":
                raise sqlite3.IntegrityError(str(error)) from error
            raise

    def commit(self):
        self.raw.commit()

    def executemany(self, sql, rows):
        for row in rows:
            self.execute(sql, row)

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type or self._broken:
                self.raw.rollback()
            else:
                self.raw.commit()
        finally:
            self.raw.close()
        return False


def connect(url):
    import psycopg
    return Connection(psycopg.connect(url.replace("postgresql+psycopg://", "postgresql://", 1)))
